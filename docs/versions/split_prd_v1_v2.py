def between(text: str, start: str, end: str) -> str:
    for s, e in ((start, end), (start.replace("\n", "\r\n"), end.replace("\n", "\r\n"))):
        m = re.search(re.escape(s) + r"(.*?)" + re.escape(e), text, flags=re.S)
        if m:
            return m.group(1).rstrip()
    raise SystemExit(f"extract failed: {start!r} .. {end!r}")


